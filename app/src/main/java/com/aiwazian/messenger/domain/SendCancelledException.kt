package com.aiwazian.messenger.domain

import java.io.IOException

/**
 * Отправлять больше нечего: локального сообщения нет в базе.
 *
 * «Отменить отправку» удаляет локальное сообщение, но цикл повторов живёт в
 * скоупе приложения и раньше об этом не узнавал: запросы продолжали уходить, а
 * запись на диске поднимала отправку заново после перезапуска. Поэтому
 * исчезновение сообщения — такой же безнадёжный отказ, как удалённый файл:
 * цикл останавливается и убирает за собой копии вместе с записью.
 *
 * Наследник IOException, а не CancellationException: отмена корутины прервала
 * бы и саму уборку.
 */
class SendCancelledException(val tempId: Long) :
    IOException("Send #$tempId was cancelled")
