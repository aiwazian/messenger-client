package com.aiwazian.messenger.ui.screens.chat.paging

/**
 * Запрос на скролл, который UI выполнит, когда нужное сообщение появится в списке.
 *
 * Почему так: окно сообщений приезжает из сети, пишется в Room и только потом доезжает до UI
 * отдельным эмитом Flow. Скроллить сразу после запроса нельзя — нужного элемента ещё нет
 * в LazyColumn. Поэтому цель кладётся в state и выполняется при пересборке списка.
 *
 * @param messageId id сообщения или null, если надо в самый низ чата.
 * @param highlight подсветить сообщение после перехода.
 * @param animate плавный скролл (для близких целей) или мгновенный прыжок.
 * @param requestId уникальный идентификатор, чтобы один и тот же переход не выполнился дважды.
 */
data class ScrollTarget(
    val messageId: Long?,
    val highlight: Boolean = false,
    val animate: Boolean = false,
    /**
     * На какой доле экрана сверху должна оказаться цель.
     *
     * 1/3 — прыжок к сообщению (виден контекст внизу),
     * 2/3 — открытие чата на первом непрочитанном: выше прочитанная история,
     * ниже попадают 1–2 непрочитанных сообщения.
     */
    val viewportFraction: Float = 1f / 3f,
    val requestId: Long = System.nanoTime()
)
