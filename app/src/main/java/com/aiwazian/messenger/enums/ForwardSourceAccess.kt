package com.aiwazian.messenger.enums

import kotlinx.serialization.Serializable

/**
 * Можно ли открыть чат-источник пересланного сообщения.
 *
 * Считается сервером на момент чтения истории: подписался на закрытый канал —
 * старые пересылки станут кликабельными сами, без перезаписи сообщений.
 */
@Serializable
enum class ForwardSourceAccess {
    /** Публичный чат, свой профиль или уже подписан — переход разрешён. */
    OPEN,
    
    /** Закрытый канал/группа или профиль скрыт настройками — показываем тултип. */
    RESTRICTED,
    
    /** Источник удалён — заголовок не кликабельный. */
    UNAVAILABLE
}
