package com.aiwazian.messenger.utils.media

import android.graphics.Color

/**
 * Пределы сжатия медиа перед отправкой — единственное место, где они заданы.
 *
 * Менять размеры нужно здесь: и вложения в сообщениях, и аватарки профиля,
 * группы и канала, и стикеры берут числа отсюда, поэтому правка одной строки
 * меняет поведение всего клиента.
 *
 * Ступени сжатия видео и их битрейты перечислены в [VideoQuality]: пользователь
 * выбирает ступень сам в предпросмотре, а отсюда берётся только та, с которой
 * видео уходит, если он этого не делал.
 */
object MediaCompressionConfig {

    /**
     * Самая длинная сторона фотографии в сообщении, в пикселях.
     *
     * Вторая сторона считается сама, пропорции сохраняются. Кадры меньше этого
     * предела не растягиваются: 100 на 100 таким и уйдёт.
     */
    const val PHOTO_MAX_DIMENSION = 1280

    /** Качество JPEG для фотографий в сообщениях, 0..100. */
    const val PHOTO_JPEG_QUALITY = 85

    /**
     * Сторона аватарки профиля, группы и канала, в пикселях.
     *
     * Аватарку обрезают в квадрат ещё до загрузки, поэтому предел один на обе
     * стороны и получается ровно 512 на 512.
     */
    const val AVATAR_MAX_DIMENSION = 512

    /** Качество JPEG для аватарок, 0..100. */
    const val AVATAR_JPEG_QUALITY = 90

    /**
     * Сторона стикера, в пикселях.
     *
     * Стикер уходит ровно квадратом: чат рисует его по одному правилу для всех
     * наборов, и подгонять сетку под каждый набор не приходится. Кадр меньше
     * предела не растягивается — он ложится в середину квадрата, а поля вокруг
     * остаются прозрачными.
     */
    const val STICKER_SIZE = 512

    /**
     * Качество WebP для стикеров, 0..100.
     *
     * Стикер разглядывают вблизи и мелким, поэтому качество выше, чем у
     * фотографии в сообщении: артефакты на контуре заметнее размера файла,
     * который при стороне 512 и так невелик.
     */
    const val STICKER_WEBP_QUALITY = 90

    /**
     * Чем заливается прозрачный фон.
     *
     * JPEG прозрачности не знает, и без заливки полупрозрачные пиксели ушли бы
     * чёрными. Белый ближе к тому, как ту же картинку рисует галерея.
     *
     * Стикеров это не касается: они собираются в WebP, где альфа сохраняется,
     * и заливать её нечем — прозрачность там и есть смысл.
     */
    const val TRANSPARENCY_BACKGROUND_COLOR = Color.WHITE

    /**
     * Форматы, которые нельзя пересобрать в JPEG, не потеряв суть: GIF и APNG
     * лишились бы анимации, SVG — векторности. Такие картинки уходят как есть.
     */
    val KEEP_AS_IS_IMAGE_MIME_TYPES = setOf(
        "image/gif",
        "image/apng",
        "image/svg+xml"
    )

    /**
     * Ступень сжатия видео для тех, кто качество не открывал.
     *
     * Выше исходного разрешения она не поднимается: видео 640 на 360 уйдёт в
     * 360p, даже если здесь стоит 720p. Растягивать кадр незачем, это только
     * добавило бы веса.
     */
    val VIDEO_DEFAULT_QUALITY = VideoQuality.P720

    /**
     * Битрейт звуковой дорожки, по которому оценивается вес, бит/с.
     *
     * Кодеку он не задаётся, там остаётся значение по умолчанию. Нужен только
     * чтобы предсказание веса в предпросмотре не разошлось с действительностью
     * на длинном видео, где звук уже заметен на фоне картинки.
     */
    const val VIDEO_AUDIO_BITRATE = 128_000
}
